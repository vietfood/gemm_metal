#!/usr/bin/env python3
"""Time the coarsening kernels at other tile sizes.

Generated by Claude (Opus 5.5); see README.md.

usage: probes/coarsening_variants.py [--write-only]

Copies kernels/1D_coarsening.metal and kernels/2D_coarsening.metal without
their template instantiations, instantiates the variants below, writes them
to $TMPDIR/metal-lab-variants/, and times each one with run_kernel.swift
(GPU time, median of 5) at M = N = K = 4096. With --write-only it only
writes the files, e.g. for profile_kernel.sh.

Every variant keeps the repository's loading scheme, in which each thread
copies one element of each tile per phase, so BK is tied to the tile sizes:
  1D: BM * BN / TM threads and BM * BK tile elements  ->  BK = BN / TM
  2D: loads loop with strides, so BK is free.
"""
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
OUT = os.path.join(os.environ.get('TMPDIR', '/tmp'), 'metal-lab-variants')
BIN = os.path.join(os.environ.get('TMPDIR', '/tmp'), 'metal-lab-profile', 'run_kernel')

ARGS = '''(
    device const float* A [[buffer(0)]],
    device const float* B  [[buffer(1)]],
    device float* C        [[buffer(2)]],
    device const GemmShape& params [[buffer(3)]],
    uint2 block_pos [[ threadgroup_position_in_grid ]],
    uint2 thread_pos [[ thread_position_in_threadgroup ]]
);
'''

# (name, BM = BN, TM) with BK = BN / TM
VARIANTS_1D = [(f'c1d_b{b}_tm{tm}', b, tm) for b, tm in
               [(32, 1), (32, 2), (32, 4), (32, 8), (32, 16), (64, 4), (64, 8), (64, 16)]]
# (name, BM = BN, BK, TM, TN)
VARIANTS_2D = [(f'c2d_b{b}_k{bk}_t{tm}x{tn}', b, bk, tm, tn) for b, bk, tm, tn in
               [(128, 8, 8, 8), (64, 8, 8, 8), (64, 8, 4, 4), (64, 16, 4, 4), (128, 8, 4, 4)]]


def body(path):
    src = open(path).read()
    return src[:src.index('template [[ host_name')]


def write():
    os.makedirs(OUT, exist_ok=True)
    src = body(os.path.join(ROOT, 'kernels', '1D_coarsening.metal'))
    for name, b, tm in VARIANTS_1D:
        src += (f'template [[ host_name("{name}") ]]\n'
                f'kernel void matmul_1D_coarsening<{b}, {b}, {b // tm}, {tm}>' + ARGS + '\n')
    open(os.path.join(OUT, '1D_variants.metal'), 'w').write(src)
    src = body(os.path.join(ROOT, 'kernels', '2D_coarsening.metal'))
    for name, b, bk, tm, tn in VARIANTS_2D:
        src += (f'template [[ host_name("{name}") ]]\n'
                f'kernel void matmul_2D_coarsening<{b}, {b}, {bk}, {tm}, {tn}>' + ARGS + '\n')
    open(os.path.join(OUT, '2D_variants.metal'), 'w').write(src)


def run(path, name, grid, threads):
    out = subprocess.run([BIN, path, name, str(grid), str(grid), str(threads), '1', '5'],
                         check=True, capture_output=True, text=True).stdout
    return float(re.search(r'([\d.]+) GFLOP/s', out).group(1))


def main():
    write()
    print(f'wrote {OUT}/1D_variants.metal and 2D_variants.metal')
    if '--write-only' in sys.argv:
        return
    if not os.path.exists(BIN):
        subprocess.run(['swiftc', '-O', os.path.join(HERE, 'run_kernel.swift'), '-o', BIN],
                       check=True)
    print('| kernel | BM=BN | BK | TM x TN | threads | loads/FMA (1D) | GFLOP/s |')
    print('|---|---:|---:|---|---:|---:|---:|')
    for name, b, tm in VARIANTS_1D:
        g = run(f'{OUT}/1D_variants.metal', name, 4096 // b, b * b // tm)
        print(f'| {name} | {b} | {b // tm} | {tm} x 1 | {b * b // tm} | {(tm + 1) / tm:.3f} | {g:.0f} |')
    for name, b, bk, tm, tn in VARIANTS_2D:
        g = run(f'{OUT}/2D_variants.metal', name, 4096 // b, b * b // (tm * tn))
        print(f'| {name} | {b} | {bk} | {tm} x {tn} | {b * b // (tm * tn)} | | {g:.0f} |')


if __name__ == '__main__':
    main()
