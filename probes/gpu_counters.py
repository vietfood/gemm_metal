#!/usr/bin/env python3
"""Report Instruments GPU counters for one kernel from a Metal System Trace.

Generated by Claude (Opus 5.5); see README.md.

usage: gpu_counters.py <trace> <function> [--all]

The trace must be recorded with the "Performance Limiters" counter profile
(profile_kernel.sh does this). Instruments samples GPU counters for the whole
GPU every few microseconds, not per dispatch, so this script keeps the
samples that overlap the GPU execution of command buffers labelled
"<function>#<i>" (the timed dispatches of run_kernel.swift) and averages each
counter, weighted by overlap time. It also reports the compiler's
register-spill events for the run_kernel process.

The counter table is large (gigabytes of XML for a few seconds), so it is
scanned in chunks with regular expressions instead of an XML parser. xctrace
writes a repeated value once with id="N" and afterwards as ref="N".
"""
import bisect
import re
import subprocess
import sys
import tempfile
import xml.etree.ElementTree as ET
from collections import defaultdict

# The counters shown by default, in report order.
REPORT = [
    'Kernel Occupancy',
    'Compute SIMD Groups Inflight',
    'Instruction Throughput Limiter',
    'Instruction Throughput Utilization',
    'ALU Utilization',
    'F32 Limiter',
    'F32 Utilization',
    'F16 Utilization',
    'Neural Accelerator Utilization',
    'Integer and Conditional Limiter',
    'Integer and Conditional Utilization',
    'Control Flow Limiter',
    'L1 Cache Limiter',
    'L1 Cache Utilization',
    'ThreadGroup L1 Read Accesses',
    'Buffer L1 Read Accesses',
    'Threadgroup Memory L1 Read Bandwidth',
    'Buffer L1 Read Bandwidth',
    'Buffer L1 Miss Rate',
    'Last Level Cache Limiter',
    'Last Level Cache Bandwidth',
    'GPU Read Bandwidth',
    'Register Pressure Influence',
]

IDS = re.compile(r'<(start-time|duration|gpu-counter-name|fixed-decimal|formatted-label) '
                 r'id="(\d+)"(?: fmt="([^"]*)")?[^>]*>([^<]*)')


def cell(tag, body):
    return rf'<{tag} (?:id="\d+"[^>]*>{body}</{tag}>|ref="(\d+)"/>)'


GPU_ROW = re.compile(r'<row>' + cell('start-time', r'(\d+)') + cell('duration', r'(\d+)') +
                     r'(?:(?!</row>).)*?<formatted-label (?:id="\d+" fmt="([^"]*)"|ref="(\d+)")')
COUNTER_ROW = re.compile(
    r'<row>' + cell('start-time', r'(\d+)') + cell('duration', r'(\d+)') +
    r'<uint32 (?:ref="\d+"/>|[^>]*>[^<]*</uint32>)' +
    cell('gpu-counter-name', r'([^<]*)') +
    r'<formatted-label (?:ref="\d+"/>|.*?</formatted-label>)' +
    cell('fixed-decimal', r'([^<]*)'))


def export(trace, schema, out):
    xpath = f'/trace-toc/run[@number="1"]/data/table[@schema="{schema}"]'
    subprocess.run(['xcrun', 'xctrace', 'export', '--input', trace, '--xpath', xpath,
                    '--output', out], check=True, stdout=subprocess.DEVNULL)


def scan(path, row_re):
    """Yield (groups, text, fmt) for every row matching row_re. Refs point
    backwards, so registering a chunk's ids before matching its rows is
    enough to resolve them with pick()."""
    text, fmt = {}, {}
    rest = ''
    with open(path, encoding='utf-8') as f:
        while True:
            chunk = f.read(1 << 26)
            if chunk:
                buf = rest + chunk
                cut = buf.rfind('</row>')
                if cut < 0:
                    rest = buf
                    continue
                part, rest = buf[:cut + 6], buf[cut + 6:]
            else:
                part, rest = rest, ''
            for _, i, f_, t in IDS.findall(part):
                text[i], fmt[i] = t, f_
            for m in row_re.finditer(part):
                yield m.groups(), text, fmt
            if not chunk:
                break


def pick(value, ref, table):
    return value if value is not None else table[ref]


def fmt_of(e):
    return e.attrib.get('fmt', '') if e is not None else ''


def small_rows(path):
    ids = {}

    def resolve(e):
        if 'ref' in e.attrib:
            return ids[e.attrib['ref']]
        if 'id' in e.attrib:
            ids[e.attrib['id']] = e
        for c in e:
            resolve(c)
        return e

    for _, e in ET.iterparse(path, events=('end',)):
        if e.tag == 'row':
            yield [resolve(c) for c in e]


def units(path):
    out = {}
    for c in small_rows(path):
        name, desc, kind = fmt_of(c[2]), fmt_of(c[5]), fmt_of(c[7])
        if kind == 'Percentage':
            out[name] = '%'
        elif 'GiB/s' in desc:
            out[name] = 'GiB/s'
        elif 'gigabytes per second' in desc:
            out[name] = 'GB/s'
        else:
            out[name] = ''
    return out


def main():
    trace, function = sys.argv[1], sys.argv[2]
    opts = sys.argv[3:]
    show_all = '--all' in opts
    # --min-ms X: select GPU intervals lasting at least X ms instead of by label,
    # for libraries that do not label their command buffers (mlx_gemm.py)
    min_ms = float(opts[opts.index('--min-ms') + 1]) if '--min-ms' in opts else None
    process = opts[opts.index('--process') + 1] if '--process' in opts else 'run_kernel'
    prefix = function + '#'
    with tempfile.TemporaryDirectory() as tmp:
        for schema in ['metal-gpu-intervals', 'metal-gpu-counter-intervals',
                       'gpu-counter-info', 'graphics-compiler-spill-events']:
            export(trace, schema, f'{tmp}/{schema}.xml')

        windows, groups = [], defaultdict(list)
        for g, text, fmt in scan(f'{tmp}/metal-gpu-intervals.xml', GPU_ROW):
            start = int(pick(g[0], g[1], text))
            dur = int(pick(g[2], g[3], text))
            label = pick(g[4], g[5], fmt)
            if min_ms is None and label.startswith(prefix):
                windows.append((start, start + dur))
            elif min_ms is not None and f'({process}' in label:
                # the GPU time-slices a command buffer with other processes, so
                # one buffer shows up as several intervals sharing its label
                groups[label].append((start, start + dur))
        busy = sorted(sum(e - s for s, e in w) for w in groups.values() if sum(e - s for s, e in w) >= (min_ms or 0) * 1e6)
        for w in groups.values():
            if sum(e - s for s, e in w) >= (min_ms or 0) * 1e6:
                windows.extend(w)
        windows.sort()
        if not windows:
            sys.exit(f'no GPU intervals labelled {prefix}<i> in {trace}' if min_ms is None
                     else f'no {process} command buffer with {min_ms} ms of GPU time in {trace}')
        starts = [w[0] for w in windows]

        acc, cover, order = defaultdict(float), defaultdict(float), []
        for g, text, fmt in scan(f'{tmp}/metal-gpu-counter-intervals.xml', COUNTER_ROW):
            start = int(pick(g[0], g[1], text))
            end = start + int(pick(g[2], g[3], text))
            # windows never overlap and a sample lasts microseconds, so only
            # the last few windows starting before `end` can overlap it
            k = bisect.bisect_right(starts, end)
            hits = [(ws, we) for ws, we in windows[max(0, k - 3):k] if we > start]
            if not hits:
                continue
            name = pick(g[4], g[5], text).split('.', 1)[-1]
            value = float(pick(g[6], g[7], text))
            for ws, we in hits:
                overlap = min(end, we) - max(start, ws)
                if overlap > 0:
                    if name not in cover:
                        order.append(name)
                    acc[name] += value * overlap
                    cover[name] += overlap

        unit = units(f'{tmp}/gpu-counter-info.xml')
        spills = sorted({fmt_of(c[3]) for c in small_rows(f'{tmp}/graphics-compiler-spill-events.xml')
                         if fmt_of(c[4]).startswith(process)})

    gpu_ms = sum(we - ws for ws, we in windows) / 1e6
    print(f'{function}: counters averaged over {gpu_ms:.1f} ms of GPU time')
    if min_ms is not None:
        print(f'  {len(busy)} command buffers with at least {min_ms} ms of GPU time, '
              f'median {busy[len(busy) // 2] / 1e6:.2f} ms')
    for name in (order if show_all else REPORT):
        if cover.get(name):
            print(f'  {name:<40} {acc[name] / cover[name]:9.2f} {unit.get(name, "")}')
    print(f'  {"Register spills":<40} {", ".join(spills) if spills else "none"}')


if __name__ == '__main__':
    main()
