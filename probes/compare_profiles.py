#!/usr/bin/env python3
"""Print saved gpu_counters.py reports side by side.

Generated by Claude (Opus 5.5); see README.md.

usage: probes/compare_profiles.py [--only "Counter A,Counter B"] [label=]<report.txt> ...

Reports are the files profile_kernel.sh writes to outputs/profiles/. A column
is named after its file unless a label is given, e.g. naive=outputs/...
"""
import os
import re
import sys


def load(arg):
    name, _, path = arg.rpartition('=')
    name = name or os.path.splitext(os.path.basename(path))[0]
    rows = {}
    for line in open(path):
        m = re.match(r'\S+: median ([\d.]+) ms, (\d+) GFLOP/s', line)
        if m:
            rows['GFLOP/s'] = (m.group(2), '')
            continue
        m = re.match(r'  (Register spills)\s{2,}(.+?)\s*$', line)
        if m:
            rows[m.group(1)] = (m.group(2), '')
            continue
        m = re.match(r'  (.+?)\s{2,}(\S+)(?: (%|GiB/s|GB/s))?\s*$', line)
        if m:
            rows[m.group(1)] = (m.group(2), m.group(3) or '')
    return name, rows


def main():
    args = sys.argv[1:]
    only = None
    if args[:1] == ['--only']:
        only = [s.strip() for s in args[1].split(',')]
        args = args[2:]
    reports = [load(p) for p in args]
    names = only or list(dict.fromkeys(k for _, rows in reports for k in rows))
    label = lambda k: k + (f' ({u})' if (u := next((r[k][1] for _, r in reports if k in r), '')) else '')
    width = max(len(label(k)) for k in names)
    cols = [max(len(n), 9) for n, _ in reports]
    print(' ' * width + '  ' + '  '.join(n.rjust(c) for (n, _), c in zip(reports, cols)))
    for k in names:
        vals = [rows.get(k, ('n/a', ''))[0] for _, rows in reports]
        print(label(k).ljust(width) + '  ' + '  '.join(v.rjust(c) for v, c in zip(vals, cols)))


if __name__ == '__main__':
    main()
